"""Live validation script for multiple real-world recommendation scenarios using Gemini LLM."""

import sys
from pathlib import Path

# Ensure root is on path
_ROOT = Path(__file__).resolve().parent
if str(_ROOT) not in sys.path:
    sys.path.insert(0, str(_ROOT))

from dotenv import load_dotenv
load_dotenv(override=True)

import pandas as pd
from src.config import PROCESSED_PARQUET
from src.filtering.engine import filter_restaurants
from src.llm.client import GeminiClient
from src.llm.recommender import generate_recommendations
from src.preferences.models import BudgetBand, UserPreferences

def run_scenario(name: str, prefs: UserPreferences, df: pd.DataFrame, client: GeminiClient):
    print(f"\n{'='*70}")
    print(f"  SCENARIO: {name}")
    print(f"{'='*70}")
    print(f"  Preferences:")
    print(f"    - Location   : {prefs.location}")
    print(f"    - Cuisine    : {prefs.cuisine}")
    print(f"    - Budget     : {prefs.budget.value}")
    print(f"    - Min Rating : {prefs.min_rating}")
    print(f"    - Additional : {prefs.additional or 'None'}")

    candidate_result = filter_restaurants(df, prefs, top_k=15, allow_relaxation=True)
    print(f"\n  Filtering Results:")
    print(f"    - Total matched : {candidate_result.total_matched}")
    print(f"    - Relaxations   : {candidate_result.relaxation_notes or 'None (Strict match)'}")

    if candidate_result.candidates_df.empty:
        print("  [ERROR] No candidates found.")
        return

    print("\n  Invoking Gemini LLM...")
    response = generate_recommendations(candidate_result, prefs, top_n=3, client=client)

    print(f"\n  LLM Status:")
    print(f"    - Provider    : {response.provider}")
    print(f"    - Model       : {response.model}")
    print(f"    - Is Fallback : {response.is_fallback}")
    print(f"\n  Summary Generated by LLM:\n    \"{response.summary}\"")

    print(f"\n  Recommendations ({len(response.recommendations)}):")
    for r in response.recommendations:
        print(f"    [{r.rank}] {r.name} | ⭐ {r.rating} | {r.estimated_cost} | {r.cuisine}")
        print(f"        Explanation: {r.explanation}")

def main():
    print("Loading Zomato dataset...")
    df = pd.read_parquet(PROCESSED_PARQUET)
    print(f"Dataset loaded: {len(df):,} restaurants")

    client = GeminiClient()
    print(f"Gemini client ready: {client.is_available()} | Active Model: {client.model}")
    assert client.is_available(), "Gemini client must have a valid API key!"

    # Scenario 1: South Indian, Low Budget (< 500), Indiranagar
    s1_prefs = UserPreferences(
        location="Indiranagar",
        cuisine="South Indian",
        budget=BudgetBand.LOW,
        min_rating=3.5,
    )
    run_scenario("South Indian on a Budget in Indiranagar", s1_prefs, df, client)

    # Scenario 2: Continental, High Budget (> 1500), Lavelle Road, Romantic
    s2_prefs = UserPreferences(
        location="Lavelle Road",
        cuisine="Continental",
        budget=BudgetBand.HIGH,
        min_rating=4.0,
        additional="romantic candle light dinner and wine",
    )
    run_scenario("Romantic High-End Continental on Lavelle Road", s2_prefs, df, client)

    # Scenario 3: Chinese, Medium Budget (500-1500), Whitefield
    s3_prefs = UserPreferences(
        location="Whitefield",
        cuisine="Chinese",
        budget=BudgetBand.MEDIUM,
        min_rating=3.8,
        additional="family dinner with outdoor seating",
    )
    run_scenario("Family Chinese Dinner in Whitefield", s3_prefs, df, client)

    print(f"\n{'='*70}")
    print("  ALL SCENARIOS COMPLETED SUCCESSFULLY WITH GEMINI LLM!")
    print(f"{'='*70}\n")

if __name__ == "__main__":
    main()
